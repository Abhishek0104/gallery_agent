"""
Single LLM client for the whole pipeline.

Provider and model per role come from config/llm.yaml. Every response is cached as one JSON file
under data/cache/llm/, keyed by (provider, model, effort, system, prompt, schema, seed), so reruns
are free and reproducible, and a single bad output can be regenerated by changing its seed.
"""
import hashlib
import json
from pathlib import Path

import yaml
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parent
FALLBACK_BETA = "server-side-fallback-2026-07-01"


class LLMError(RuntimeError):
    pass


class LLM:
    def __init__(self, role="generation", config_path=ROOT / "config" / "llm.yaml"):
        cfg = yaml.safe_load(Path(config_path).read_text())
        spec = cfg["roles"][role]
        if not spec.get("model"):
            raise LLMError(f"no model configured for role {role!r} in {config_path}")
        self.provider = cfg["provider"]
        self.model = spec["model"]
        self.effort = spec.get("effort", "high")
        self.max_tokens = spec.get("max_tokens", 16000)
        self.fallbacks = cfg.get("fallbacks")
        self.cache_dir = ROOT / cfg["cache_dir"]
        self._client = None

    # ------------------------------------------------------------------ public
    def json(self, prompt: str, schema: type[BaseModel], seed, system: str = "") -> dict:
        """Structured output validated against `schema`; returns a plain dict."""
        schema_json = json.dumps(schema.model_json_schema(), sort_keys=True)
        key = self._key(system, prompt, schema_json, seed)
        path = self.cache_dir / f"{key}.json"
        if path.exists():
            return json.loads(path.read_text())["output"]

        output = self._call_json(system, prompt, schema)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({
            "provider": self.provider, "model": self.model, "effort": self.effort,
            "seed": seed, "system": system, "prompt": prompt, "schema": schema.__name__,
            "output": output,
        }, indent=2, ensure_ascii=False))
        return output

    def cached(self, prompt: str, schema: type[BaseModel], seed, system: str = "") -> bool:
        schema_json = json.dumps(schema.model_json_schema(), sort_keys=True)
        return (self.cache_dir / f"{self._key(system, prompt, schema_json, seed)}.json").exists()

    # ------------------------------------------------------------------ internals
    def _key(self, system, prompt, schema_json, seed):
        blob = json.dumps([self.provider, self.model, self.effort, system, prompt, schema_json, str(seed)])
        return hashlib.sha256(blob.encode()).hexdigest()[:24]

    def _call_json(self, system, prompt, schema):
        if self.provider != "anthropic":
            raise LLMError(f"unsupported provider {self.provider!r}")
        import anthropic

        if self._client is None:
            self._client = anthropic.Anthropic()
        kwargs = dict(
            model=self.model,
            max_tokens=self.max_tokens,
            messages=[{"role": "user", "content": prompt}],
            output_format=schema,
            output_config={"effort": self.effort},
        )
        if system:
            kwargs["system"] = system
        if self.fallbacks:
            kwargs.update(betas=[FALLBACK_BETA], fallbacks=self.fallbacks)
        try:
            resp = self._client.beta.messages.parse(**kwargs)
        except anthropic.AuthenticationError as e:
            raise LLMError("no valid Anthropic credentials: set ANTHROPIC_API_KEY") from e
        except TypeError as e:          # SDK raises this when no credential resolves at all
            if "api_key" in str(e) or "auth" in str(e).lower():
                raise LLMError("no Anthropic credentials: set ANTHROPIC_API_KEY") from e
            raise
        if resp.stop_reason == "refusal":
            raise LLMError(f"model refused (request {resp._request_id}): {resp.stop_details}")
        if resp.stop_reason == "max_tokens":
            raise LLMError(f"output truncated at max_tokens={self.max_tokens}")
        if resp.parsed_output is None:
            raise LLMError(f"no parsed output (stop_reason={resp.stop_reason})")
        return resp.parsed_output.model_dump()
